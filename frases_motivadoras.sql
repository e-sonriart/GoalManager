-- Frases motivadoras por equipo (una frase activa por equipo, con título "FRASE DEL DIA")
-- Ejecutar en el SQL Editor de Supabase (idempotente).
-- Estado previo real de la tabla frases_motivadoras_365:
--   * Ya tiene equipo, creadaen y creadapor (¡en minúsculas!), RLS con política de acceso y default/identity en id.
--   * Dos problemas que este script corrige:
--     1) La app escribe "creadaEn" / "creadaPor" (camelCase): hay que renombrar las columnas en minúsculas.
--     2) La secuencia de id empezó en 1 con ~365 filas ya creadas: los inserts fallaban con clave duplicada (409).

-- Equipo al que pertenece la frase (vacío = todo el club)
alter table frases_motivadoras_365 add column if not exists equipo text default '';
-- Frase fijada a mano por entrenador/admin; si es false la frase forma parte del banco
-- que la tarjeta rota cada día de forma aleatoria.
alter table frases_motivadoras_365 add column if not exists fija boolean default false;

-- Renombrar columnas creadas en minúsculas a camelCase (lo que espera la app)
do $$
begin
  if exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'frases_motivadoras_365' and column_name = 'creadaen'
     )
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'frases_motivadoras_365' and column_name = 'creadaEn'
     ) then
    alter table frases_motivadoras_365 rename column creadaen to "creadaEn";
  end if;
  if exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'frases_motivadoras_365' and column_name = 'creadapor'
     )
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'frases_motivadoras_365' and column_name = 'creadaPor'
     ) then
    alter table frases_motivadoras_365 rename column creadapor to "creadaPor";
  end if;
end $$;

-- Cuándo y quién la activó (para mostrar "— autor" bajo la frase); comillas para que PG no pase a minúsculas
alter table frases_motivadoras_365 add column if not exists "creadaEn" timestamptz default now();
alter table frases_motivadoras_365 add column if not exists "creadaPor" text default '';

-- El id numérico se rellena solo al insertar (por si la tabla se creó sin autoincremento)
do $$
begin
  if exists (
    select 1 from pg_attribute a
    where a.attrelid = 'frases_motivadoras_365'::regclass
      and a.attname = 'id'
      and a.attidentity = ''
      and a.attgenerated = ''
      and not exists (
        select 1 from pg_attrdef d
        where d.adrelid = a.attrelid and d.adnum = a.attnum
      )
  ) then
    execute 'alter table frases_motivadoras_365 alter column id add generated by default as identity';
  end if;
end $$;

-- Reajustar la secuencia del id al máximo actual (evita "duplicate key value violates unique constraint")
do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('frases_motivadoras_365', 'id');
  if seq is not null and exists (select 1 from frases_motivadoras_365) then
    execute format(
      'select setval(%L::regclass, coalesce((select max(id) from frases_motivadoras_365), 1), true)',
      seq
    );
  end if;
end $$;

-- Acceso completo con la anon key (mismo modelo RLS abierto que el resto de tablas)
alter table frases_motivadoras_365 enable row level security;

drop policy if exists "frases_motivadoras_365_acceso" on frases_motivadoras_365;
create policy "frases_motivadoras_365_acceso" on frases_motivadoras_365
  for all
  using (true)
  with check (true);
