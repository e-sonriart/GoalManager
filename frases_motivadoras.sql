-- Frases motivadoras por equipo (una frase activa por equipo, con título "FRASE DEL DIA")
-- Ejecutar una vez en el SQL Editor de Supabase (idempotente).
-- La tabla frases_motivadoras_365 ya existe con: id (bigint), frase y categoria.

-- Equipo al que pertenece la frase (vacío = todo el club)
alter table frases_motivadoras_365 add column if not exists equipo text default '';
-- Cuándo y quién la activó (para mostrar "— autor" bajo la frase)
alter table frases_motivadoras_365 add column if not exists creadaEn timestamptz default now();
alter table frases_motivadoras_365 add column if not exists creadaPor text default '';

-- El id numérico se rellena solo al insertar (por si la tabla se creó sin autoincremento)
do $$
begin
  if exists (
    select 1 from pg_attribute
    where attrelid = 'frases_motivadoras_365'::regclass
      and attname = 'id'
      and attidentity = ''
      and attgenerated = ''
      and not atthasdefault
  ) then
    execute 'alter table frases_motivadoras_365 alter column id add generated by default as identity';
  end if;
end $$;

-- Acceso completo con la anon key (mismo modelo RLS abierto que el resto de tablas)
alter table frases_motivadoras_365 enable row level security;

drop policy if exists "frases_motivadoras_365_acceso" on frases_motivadoras_365;
create policy "frases_motivadoras_365_acceso" on frases_motivadoras_365
  for all
  using (true)
  with check (true);
